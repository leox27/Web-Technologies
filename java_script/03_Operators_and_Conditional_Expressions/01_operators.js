// ###Operators in JavaScript

console.log("Operators in JavaScript");

// ##1. Arithmetic Operators
let a = 10;
let b = 5;
console.log("a + b =", a + b); // Addition
console.log("a - b =", a - b); // Subtraction
console.log("a * b =", a * b); // Multiplication
console.log("a / b =", a / b); // Division
console.log("a % b =", a % b); // Modulus
console.log("a ** b =", a ** b); // Exponentiation
console.log("++a =", ++a); // Pre-increment
console.log("a++ =", a++); // Post-increment
console.log("--b =", --b); // Pre-decrement
console.log("b-- =", b--); // Post-decrement

// ##2. Assignment Operators
let c = 10;
console.log("c =", c);
c += 5;
console.log("c += 5 =>", c); // Addition assignment
c -= 3;
console.log("c -= 3 =>", c); // Subtraction assignment
c *= 2;
console.log("c *= 2 =>", c); // Multiplication assignment
c /= 4;
console.log("c /= 4 =>", c); // Division assignment
c %= 3;
console.log("c %= 3 =>", c); // Modulus assignment
c **= 2;
console.log("c **= 2 =>", c); // Exponentiation assignment
c = 10; // Reset c for further operations


// ##3. Comparison Operators
let x = 10;
let y = 20;
console.log("x == y =>", x == y); // Equality
console.log("x != y =>", x != y); // Inequality
console.log("x > y =>", x > y); // Greater than
console.log("x < y =>", x < y); // Less than
console.log("x >= y =>", x >= y); // Greater than or equal to
console.log("x <= y =>", x <= y); // Less than or equal to
console.log("x === y =>", x === y); // Strict equality
console.log("x !== y =>", x !== y); // Strict inequality


// ##4. Logical Operators
let p = true;
let q = false;
console.log("p && q =>", p && q); // Logical AND
console.log("p || q =>", p || q); // Logical OR
console.log("!p =>", !p); // Logical NOT

console.log("!false =>", !false); // Logical NOT of false
console.log("!true =>", !true); // Logical NOT of true

